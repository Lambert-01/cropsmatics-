def _resolve(payload: QueryIn) -> QueryOut:
    """Resolve an intent to structured evidence. Language-independent."""
    question = payload.question.lower()

    # Refuse topics the published statistics cannot support *before* looking for
    # entities, so a question about prices or weather is never answered with an
    # unrelated production figure.
    unsupported_topic = mentions(question, UNSUPPORTED_HINTS)
    if unsupported_topic:
        return _unsupported("unsupported", unsupported_topic=unsupported_topic)

    district, crop = extract(payload.question)

    # A page may send its own selection as structured context. It only names
    # entities (never values), and an entity the question states explicitly still
    # wins, so the context narrows grounding without overriding the user.
    requested_period: str | None = None
    context = payload.context
    if context is not None:
        if context.period_code:
            try:
                requested_period = period_service.require(context.period_code)
            except period_service.UnknownPeriodError:
                requested_period = None
        district = district or context.district
        crop = crop or context.crop

    if district is not None and crop is not None:
        return _district_crop_gap(district, crop, period_code=requested_period)
    if crop is not None:
        return _crop_context(crop, period_code=requested_period)
    if district is not None:
        return _district_context(district, period_code=requested_period)

    indicator_ids = matched_indicators(question)
    if indicator_ids:
        return _national_indicator(indicator_ids)

    return _unsupported("unsupported")


@router.post("/query", response_model=QueryOut)
def query(payload: QueryIn) -> QueryOut:
    """Answer a question strictly from validated Cropmatics data.

    Intent resolution and numeric computation happen once; the requested
    language only changes the rendered prose (never the evidence).
    """
    result = _resolve(payload)
    language = assistant_language.normalize_language(payload.language)
    answer, translation_status = assistant_language.render(
        answer_en=result.answer,
        grounded=result.grounded,
        language=language,
    )
    result.answer = answer
    result.language = language
    result.translation_status = translation_status
    result.key_figures = _key_figures(result.intent, result.evidence)
    return result

