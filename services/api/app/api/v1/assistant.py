"""Grounded AI explanation endpoint.

The assistant is an **explanation layer**, not a source of numbers. It extracts
entities from the question, retrieves validated analytics through the same
services the structured endpoints use, and composes an answer strictly from those
values. No number in an answer is generated by a model.

Every answer exposes the source, the period, the coverage and the limitations of
the evidence behind it. When a question cannot be grounded in the published data
the assistant says so instead of guessing:

    "Cropmatics does not currently have verified data to answer this question."

An LLM may be added later as a *rephrasing* layer over exactly this retrieved
evidence; it must never be given the freedom to state a figure.
"""

