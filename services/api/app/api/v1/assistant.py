def mentions(text: str, hints: tuple[str, ...]) -> str | None:
    """Return the first hint that appears as a whole word, else ``None``."""
    for hint in hints:
        pattern = r"(?<![a-z0-9])" + re.escape(hint) + r"(?![a-z0-9])"
        if re.search(pattern, text):
            return hint
    return None



class QueryContext(BaseModel):
    """Structured evidence supplied by the calling page.

    A contextual action such as "Explain this yield pattern" must ground its
    answer in the selection the page is actually showing, not in whichever
    release happens to be the default. The context therefore only *names*
    entities (period, crop, district, metric); it can never carry a value, so it
    cannot be used to inject a figure into an answer.
    """

    page: str | None = Field(None, description="originating screen, e.g. yield-intelligence")
    metric: str | None = None
    period_code: str | None = Field(None, description="published period, e.g. 2026B")
    crop: str | None = None
    district: str | None = None
    province: str | None = None
    benchmark_strategy: str | None = None


class QueryIn(BaseModel):
    question: str = Field(min_length=2, max_length=500)
    language: str = "en"
    context: QueryContext | None = None


class QueryOut(BaseModel):
    answer: str
    grounded: bool
    intent: str = "unsupported"
    evidence: dict = Field(default_factory=dict)
    # Normalized figures for the answer, so the mobile client can render "key
    # figures" without parsing prose. Identical across languages.
    key_figures: list[dict] = Field(default_factory=list)
    # --- language metadata --------------------------------------------------
    language: str = "en"
    # None on English; otherwise how the Kinyarwanda text was produced.
    translation_status: str | None = None
    # --- grounding metadata (always present on a grounded answer) -----------
    source: str | None = None
    period: str | None = None
    coverage: str | None = None
    limitations: list[str] = Field(default_factory=list)


def _key_figures(intent: str, evidence: dict) -> list[dict]:
    """Flatten the headline numbers of an answer into a language-neutral list."""
    figures: list[dict] = []
    if intent == "district_crop_gap":
        if evidence.get("observed_yield_kg_ha") is not None:
            figures.append(
                {"label": "observed yield", "value": evidence["observed_yield_kg_ha"],
                 "unit": "kg/ha"}
            )
        if evidence.get("benchmark_yield_kg_ha") is not None:
            figures.append(
                {"label": "national crop median",
                 "value": evidence["benchmark_yield_kg_ha"], "unit": "kg/ha"}
            )
    elif intent == "crop_national_context":
        for key, label, unit in (
            ("production_mt", "production", "metric tonnes"),
            ("harvested_area_ha", "harvested area", "ha"),
            ("yield_mt_ha", "yield", "t/ha"),
            ("yield_kg_ha", "yield", "kg/ha"),
        ):
            if evidence.get(key) is not None:
                figures.append({"label": label, "value": evidence[key], "unit": unit})
    elif intent == "national_indicator":
        for item in evidence.get("indicators", []):
            figures.append(
                {"label": item.get("label"), "value": item.get("mean"),
                 "unit": item.get("unit")}
            )
    elif intent == "district_context":
        figures.append(
            {"label": "crops with published data", "value": evidence.get("n_crops_with_data"),
             "unit": "crops"}
        )
    return [f for f in figures if f.get("value") is not None]


def _find_entity(question: str, vocabulary: list[str]) -> str | None:
    """Longest whole-word case-insensitive match against a known vocabulary.

    Whole-word matching matters: a naive substring test would match "rice" inside
    "price" and answer the wrong question. Choosing the longest match means
    "Paddy rice" wins over "rice" when both are present.
    """
    best: str | None = None
    for value in vocabulary:
        if not value:
            continue
        pattern = r"(?<![a-z0-9])" + re.escape(str(value).lower()) + r"(?![a-z0-9])"
        if re.search(pattern, question) and (best is None or len(str(value)) > len(best)):
            best = str(value)
    return best


def extract(question: str) -> tuple[str | None, str | None]:
    """Resolve a district and a crop from a free-text question."""
    q = question.lower()
    try:
        districts = [str(v) for v in repo.districts()["district"].dropna()]
        vocabulary = crop_vocabulary()
    except Exception:
        return None, None

    district = _find_entity(q, districts)
    key = _find_entity(q, list(vocabulary))
    return district, vocabulary.get(key) if key else None


def crop_vocabulary() -> dict[str, str]:
    """Map every accepted crop phrase (lower-cased) to its canonical crop name.

    Built from the crop dictionary, so it can never drift from the data:

    * the published crop name itself ("paddy rice");
    * its Kinyarwanda name ("umuceri");
    * a trailing word, but **only when it is unambiguous** — "rice" resolves to
      "Paddy rice", while "potato" is rejected because it fits both Irish and
      sweet potato, and "crops" because it fits two residual categories.
    """
    frame = repo.crops()
    names = [str(v) for v in frame["crop_name"].dropna()]
    canonical = {name.lower() for name in names}

    vocabulary: dict[str, str] = {name.lower(): name for name in names}

    if "kinyarwanda_name" in frame.columns:
        for _, row in frame.iterrows():
            local = row.get("kinyarwanda_name")
            if local:
                vocabulary.setdefault(str(local).lower(), str(row["crop_name"]))

    trailing: dict[str, set[str]] = {}
    for name in names:
        tokens = re.split(r"[^a-z]+", name.lower())
        last = tokens[-1] if tokens else ""
        if last and last not in canonical:
            trailing.setdefault(last, set()).add(name)
    for alias, owners in trailing.items():
        if len(owners) == 1:
            vocabulary.setdefault(alias, next(iter(owners)))

    return vocabulary


