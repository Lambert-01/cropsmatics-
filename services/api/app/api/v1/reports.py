@router.get("/district-summary")
def district_summary(
    district: str, f: AnalyticsFilters = Depends(analytics_filters)
) -> dict:
    """Per-crop summary for one district in the selected period.

    The provenance names the period and source of the rows actually returned, so
    it cannot describe a release the response did not come from.
    """
    frame = _district_panel(f)
    sub = frame[frame["district"].astype(str).str.lower() == district.lower()]
    if sub.empty:
        raise HTTPException(
            status.HTTP_404_NOT_FOUND,
            f"no published district data for {district!r} in this selection",
        )

    valid = sub[sub["yield_kg_ha"].fillna(0) > 0]
    by_crop = (
        valid.groupby("canonical_crop_name")
        .agg(
            crop_yield_median_kg_ha=("yield_kg_ha", "median"),
            production_mt=("production_mt", "sum"),
            harvested_area_ha=("harvested_area_ha", "sum"),
        )
        .reset_index()
        .rename(columns={"canonical_crop_name": "crop"})
    )
    by_crop = by_crop.where(pd.notna(by_crop), None)
    period_code = analytics_service.frame_period_code(sub)
    return {
        "district": district,
        "period_code": period_code,
        "crops": by_crop.to_dict(orient="records"),
        "provenance": Provenance(
            source_id=analytics_service.frame_source_id(sub),
            source_period=period_code,
            method="aggregation of published district x crop rows for the selected period",
            limitations=[
                "district aggregates; within-district variation is not shown",
                "a yield is only comparable within one crop",
            ],
        ).model_dump(),
    }


@router.get("/crop-summary")
def crop_summary(crop: str, f: AnalyticsFilters = Depends(analytics_filters)) -> dict:
    # The benchmark (and therefore the median gap) is computed over the
    # reference population before any district inspection filter is applied.
    ref = analytics_service.reference_filters(f)
    frame = _district_panel(ref)
    sub = frame[frame["canonical_crop_name"].astype(str).str.lower() == crop.lower()]
    if sub.empty:
        raise HTTPException(
            status.HTTP_404_NOT_FOUND,
            f"no published district data for {crop!r} in this selection",
        )
    valid = sub[sub["yield_kg_ha"].fillna(0) > 0]
    g = analytics_service.gapped(sub, f.benchmark_strategy)
    if f.district:
        g = apply_filters(g, f)
        valid = apply_filters(valid, f)
    period_code = analytics_service.frame_period_code(sub)
    return {
        "crop": crop,
        "period_code": period_code,
        "districts": int(valid["district"].nunique()),
        "median_yield_kg_ha": None if valid.empty else round(float(valid["yield_kg_ha"].median()), 1),
        "total_production_mt": None if valid.empty else round(float(valid["production_mt"].sum()), 1),
        "median_gap_index": None if g.empty else round(float(g["gap_index"].median()), 2),
        "provenance": Provenance(
            source_id=analytics_service.frame_source_id(sub),
            source_period=period_code,
            method="district rows for the selected period, with the selected benchmark",
            limitations=["district aggregates only", "association, not causation"],
        ).model_dump(),
    }


