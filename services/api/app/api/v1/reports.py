def _district_panel(f: AnalyticsFilters) -> pd.DataFrame:
    """District rows of the multi-period panel, filtered.

    Restricted to ``geography_level == "DISTRICT"`` and, defensively, to
    ``farmer_scale == "all"``: the panel carries large/small-scale farm
    sub-rows, and adding one of those to its district total would double count
    a district's area and production.
    """
    panel = repo.crop_productivity()
    if "geography_level" in panel.columns:
        panel = panel[panel["geography_level"].astype(str).str.upper() == "DISTRICT"]
    if "farmer_scale" in panel.columns:
        scale = panel["farmer_scale"].astype(str).str.lower()
        panel = panel[panel["farmer_scale"].isna() | (scale == "all")]
    return apply_filters(panel, f)


def _quality_flags(frame: pd.DataFrame, reported_col: str | None) -> pd.Series:
    """Per-row quality flag for one indicator.

    ``synthetic`` wins over ``derived``: a fixture row is not an observation at
    all, so it must never be described merely as computed.
    """
    flag = pd.Series("", index=frame.index, dtype=object)
    if reported_col and reported_col in frame.columns:
        reported = frame[reported_col].astype("boolean").fillna(False).astype(bool)
        flag[~reported] = "derived"
    if "is_synthetic" in frame.columns:
        synthetic = frame["is_synthetic"].astype("boolean").fillna(False).astype(bool)
        flag[synthetic] = "synthetic"
    return flag


def to_long_format(frame: pd.DataFrame) -> pd.DataFrame:
    """Reshape a productivity frame into the canonical long export.

    One row per observation: ``period / geography / crop / indicator / value /
    unit / source / quality flag``. A ``derived`` flag means the yield was
    computed from the published harvested area and production rather than
    published directly.
    """
    if frame.empty:
        return pd.DataFrame(columns=list(LONG_COLUMNS))

    base = [
        c
        for c in (
            "period_code",
            "year",
            "season",
            "geography_level",
            "province",
            "district",
            "district_code",
            "canonical_crop_name",
            "source_id",
        )
        if c in frame.columns
    ]

    parts: list[pd.DataFrame] = []
    for column, indicator, unit, reported_col in INDICATORS:
        if column not in frame.columns:
            continue
        part = frame[base + [column]].copy()
        part = part.rename(columns={column: "value"})
        part["indicator"] = indicator
        part["unit"] = unit
        part["quality_flag"] = _quality_flags(frame, reported_col)
        parts.append(part)

    if not parts:
        return pd.DataFrame(columns=list(LONG_COLUMNS))

    out = pd.concat(parts, ignore_index=True)
    # A blank value is "not measured", so it is dropped rather than written as 0.
    out = out[out["value"].notna()]
    out = out.rename(columns={"period_code": "period", "canonical_crop_name": "crop"})
    for column in LONG_COLUMNS:
        if column not in out.columns:
            out[column] = None
    out["value"] = pd.to_numeric(out["value"], errors="coerce").round(4)
    out = out[out["value"].notna()]
    return out[list(LONG_COLUMNS)].sort_values(
        [c for c in ("period", "district", "crop", "indicator") if c in out.columns]
    )


def _scorecard(f: AnalyticsFilters) -> pd.DataFrame:
    """One row per district x crop: the published measures plus the gap.

    Yield and the benchmark are returned as reported; the gap is the documented
    ``100 * (1 - yield / benchmark)`` transform. Nothing is averaged across
    crops, because a cross-crop mean yield is not an agricultural quantity.

    The benchmark is computed over the reference population (the district
    inspection dropped) and the rows are narrowed afterwards, so exporting one
    district never redefines its own benchmark.
    """
    ref = analytics_service.reference_filters(f)
    frame = _district_panel(ref)
    if frame.empty:
        return pd.DataFrame()

    gapped = analytics_service.gapped(frame, f.benchmark_strategy)
    if f.district:
        gapped = apply_filters(gapped, f)
    if gapped.empty:
        return pd.DataFrame()

    keep = [
        c
        for c in (
            "period_code",
            "year",
            "season",
            "province",
            "district",
            "district_code",
            "canonical_crop_name",
            "cultivated_area_ha",
            "harvested_area_ha",
            "production_mt",
            "yield_kg_ha",
            "benchmark_yield_kg_ha",
            "gap_index",
            "source_id",
        )
        if c in gapped.columns
    ]
    out = gapped[keep].copy()
    out["benchmark_strategy"] = f.benchmark_strategy
    out["yield_source"] = np.where(
        gapped.get("yield_reported", pd.Series(True, index=gapped.index))
        .astype("boolean")
        .fillna(True)
        .astype(bool),
        "published",
        "derived",
    )
    out = out.rename(
        columns={
            "period_code": "period",
            "canonical_crop_name": "crop",
        }
    )
    return out.sort_values(["period", "district", "crop"])


def _yield_gaps(f: AnalyticsFilters, limit: int) -> pd.DataFrame:
    scorecard = _scorecard(f)
    if scorecard.empty or "gap_index" not in scorecard.columns:
        return pd.DataFrame()
    out = scorecard[scorecard["gap_index"].notna()]
    return out.sort_values("gap_index", ascending=False).head(limit)


def _crop_profile(f: AnalyticsFilters) -> pd.DataFrame:
    """Per-period national summary for one crop, across every published period.

    Deliberately ignores the period filter: the point of a crop profile is the
    series, and honouring a single-period filter would return one row and hide
    that a series exists. The crop filter is required.
    """
    if not f.crop:
        raise HTTPException(
            status.HTTP_422_UNPROCESSABLE_ENTITY,
            "crop is required: a crop profile describes one crop across periods",
        )
    frame = _district_panel(f)
    if frame.empty:
        return pd.DataFrame()

    valid = frame[frame["yield_kg_ha"].fillna(0) > 0]
    rows: list[dict] = []
    for period, group in frame.groupby("period_code", dropna=True):
        group_valid = valid[valid["period_code"] == period] if not valid.empty else valid
        rows.append(
            {
                "period": period,
                "crop": f.crop,
                "districts_with_area": int(group["district_code"].nunique()),
                "districts_with_yield": int(group_valid["district_code"].nunique())
                if not group_valid.empty
                else 0,
                # Area and production are additive, so they are summed.
                "cultivated_area_ha": round(float(group["cultivated_area_ha"].sum()), 2)
                if group["cultivated_area_ha"].notna().any()
                else None,
                "harvested_area_ha": round(float(group["harvested_area_ha"].sum()), 2)
                if group["harvested_area_ha"].notna().any()
                else None,
                "production_mt": round(float(group["production_mt"].sum()), 2)
                if group["production_mt"].notna().any()
                else None,
                "mean_district_yield_kg_ha": None
                if group_valid.empty
                else round(float(group_valid["yield_kg_ha"].mean()), 1),
                "median_district_yield_kg_ha": None
                if group_valid.empty
                else round(float(group_valid["yield_kg_ha"].median()), 1),
                "source_id": ", ".join(
                    sorted({str(v) for v in group["source_id"].dropna() if str(v)})
                )
                or None,
            }
        )

    out = pd.DataFrame(rows)
    if out.empty:
        return out
    # Aggregated yield = total production / total harvested area, in the source
    # units (mt over ha -> kg/ha after the 1000x conversion).
    harvested = pd.to_numeric(out["harvested_area_ha"], errors="coerce")
    production = pd.to_numeric(out["production_mt"], errors="coerce")
    with np.errstate(divide="ignore", invalid="ignore"):
        out["yield_kg_ha"] = np.where(
            harvested > 0, (production / harvested) * 1000.0, np.nan
        )
    out["yield_kg_ha"] = out["yield_kg_ha"].round(1)
    return out.sort_values("period")


