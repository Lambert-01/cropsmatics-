"""Canonical reporting endpoints.

Every export is generated by Python from the same processed tables the interface
reads, so a downloaded file always matches what is on screen. The historical
single-release exports (``district_crop_productivity``, ``district_factors``,
``national_crop_trends``) are no longer the primary catalogue: the platform is
multi-period, so its reports are too.

Design rules:

* **A report is period-aware.** The canonical exports read the multi-period
  ``crop_productivity`` panel and honour the same ``period_code`` / ``crop`` /
  ``province`` / ``district`` / ``benchmark_strategy`` filters as every other
  analytical endpoint. With no period selected they span every published period
  rather than silently defaulting to one release.
* **A report says what it is.** Long-format exports carry ``indicator``,
  ``unit``, ``source_id`` and ``quality_flag`` per row, so a value is never
  separable from its unit or its provenance. ``quality_flag`` marks a row
  ``derived`` when the source published an area and a production figure but no
  yield (the platform computed it) and ``synthetic`` when a row is a fixture -
  the export never presents a modelled number as a published one.
* **Geography is never mixed.** District reports read district rows only; the
  national context series stays at national level and is labelled as such.
  A national row is never written into a district export.
* **CSV is the default.** JSON is available where a consumer needs it; PDF is a
  branded decision brief generated from the same rows, not a second calculation.
"""

